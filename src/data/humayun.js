// A book's "ধরন" comes from its ideal-list group; appendix entries use their sub-group.
export function categoryForCatalogEntry(entry) {
  if (!entry) return '';
  if (entry.group === 'g12') {
    if (entry.note.startsWith('শিশু-কিশোর')) return 'শিশু-কিশোর';
    if (entry.note.startsWith('উপন্যাস')) return 'উপন্যাস';
    if (entry.note.startsWith('ভূত')) return 'ভূত ও রহস্য';
    return entry.note.split(' · ')[0];
  }
  if (entry.group === 'g13') return '';
  return HUMAYUN_GROUPS.find((g) => g.id === entry.group)?.label || '';
}
